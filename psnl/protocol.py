    "MAGIC",
    "SYNC_BYTE",
    "HOST_SLOT",
    "NO_SLOT",
    "MAX_PAYLOAD",
    "MAX_EVENT_PAYLOAD",
    "FLAG_REBIND",
    "PacketType",
